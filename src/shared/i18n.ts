const dictionaries: Record<Language, Dict> = { zh, en };

export function translate(language: Language, key: string, params?: Record<string, string | number>): string {
  const dict = dictionaries[language] ?? dictionaries.zh;
  let text = dict[key] ?? dictionaries.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}
